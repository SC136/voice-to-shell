"""
Shell Execution Component: Docker & Emergency Luminaire Mesh Engine
Executes commands generated by the TTC component.
Provides:
1. Docker Engine (real execution or mock IoT edge daemon)
2. Emergency Luminaires Mesh Controller (complete simulation of the 53 proprietary commands)
"""

import shutil
import subprocess
import json
import random
from typing import Dict, Any, List, Optional


class ExecutionResult:
    """Standardized shell execution response."""

    def __init__(self, command: str, stdout: str, stderr: str = "", returncode: int = 0, simulated: bool = False):
        self.command = command
        self.stdout = stdout
        self.stderr = stderr
        self.returncode = returncode
        self.simulated = simulated

    def to_dict(self) -> Dict[str, Any]:
        return {
            "command": self.command,
            "stdout": self.stdout,
            "stderr": self.stderr,
            "returncode": self.returncode,
            "simulated": self.simulated,
            "success": self.returncode == 0
        }

    def __repr__(self) -> str:
        tag = "[SIMULATED]" if self.simulated else "[REAL]"
        return f"{tag} $ {self.command}\n{self.stdout}" if self.returncode == 0 else f"{tag} $ {self.command} (failed: {self.stderr})"


class DockerExecutor:
    """Handles Docker commands either on host Docker daemon or via edge container simulator."""

    def __init__(self, force_mock: bool = False):
        self.has_docker = bool(shutil.which("docker")) and not force_mock
        self.mock_containers = {
            "grafana": {"id": "a1b2c3d4e5f6", "image": "grafana/grafana:latest", "status": "Up 4 hours", "ports": "0.0.0.0:3000->3000/tcp"},
            "ubuntu": {"id": "f6e5d4c3b2a1", "image": "ubuntu:22.04", "status": "Up 2 days", "size": "72.8MB"},
            "nginx": {"id": "c3d4e5f6a1b2", "image": "nginx:alpine", "status": "Up 1 day", "ports": "0.0.0.0:80->80/tcp"},
            "prometheus": {"id": "d4e5f6a1b2c3", "image": "prom/prometheus:latest", "status": "Up 3 hours", "ports": "0.0.0.0:9090->9090/tcp"},
            "iot_gateway": {"id": "e5f6a1b2c3d4", "image": "edge/iot-gateway:v1.2", "status": "Up 5 days", "ports": "0.0.0.0:1883->1883/tcp"}
        }
        self.mock_images = [
            {"repository": "ubuntu", "tag": "22.04", "id": "74af7cb41508", "size": "77.8MB"},
            {"repository": "grafana/grafana", "tag": "latest", "id": "3c983d5a498b", "size": "342MB"},
            {"repository": "nginx", "tag": "alpine", "id": "9a0a80e781bc", "size": "23.5MB"},
            {"repository": "prom/prometheus", "tag": "latest", "id": "18f1a48c1e7a", "size": "208MB"}
        ]
        self.mock_volumes = ["grafana_data", "prometheus_data", "iot_logs"]

    def execute(self, command: str) -> ExecutionResult:
        """Execute command in docker environment."""
        if not command.startswith("docker"):
            return ExecutionResult(command, "", "Error: Not a docker command", returncode=1)

        if self.has_docker:
            try:
                proc = subprocess.run(
                    command,
                    shell=True,
                    capture_output=True,
                    text=True,
                    timeout=10
                )
                return ExecutionResult(command, proc.stdout, proc.stderr, proc.returncode, simulated=False)
            except Exception as e:
                # Fall back to simulated execution
                pass

        return self._simulate(command)

    def _simulate(self, command: str) -> ExecutionResult:
        parts = command.split()
        if len(parts) < 2:
            return ExecutionResult(command, "Docker version 24.0.7, build afdd53b", simulated=True)

        action = parts[1]

        if action in ("ps", "container"):
            lines = ["CONTAINER ID   IMAGE                 COMMAND                  STATUS         PORTS                    NAMES"]
            for name, info in self.mock_containers.items():
                lines.append(f"{info['id']}   {info['image']:<21} \"entrypoint.sh\"        {info['status']:<14} {info.get('ports', ''):<24} {name}")
            return ExecutionResult(command, "\n".join(lines), simulated=True)

        elif action == "images" or (action == "image" and "ls" in parts):
            lines = ["REPOSITORY            TAG       IMAGE ID       SIZE"]
            for img in self.mock_images:
                lines.append(f"{img['repository']:<21} {img['tag']:<9} {img['id']:<14} {img['size']}")
            return ExecutionResult(command, "\n".join(lines), simulated=True)

        elif action == "kill":
            target = parts[-1]
            return ExecutionResult(command, f"{target}", simulated=True)

        elif action == "stop":
            target = parts[-1]
            return ExecutionResult(command, f"{target}", simulated=True)

        elif action == "start":
            target = parts[-1]
            return ExecutionResult(command, f"{target}", simulated=True)

        elif action == "restart":
            target = parts[-1]
            return ExecutionResult(command, f"{target}", simulated=True)

        elif action == "rm":
            target = parts[-1]
            return ExecutionResult(command, f"{target}", simulated=True)

        elif action == "inspect":
            target = parts[-1]
            mock_inspect = [{
                "Id": "f6e5d4c3b2a19876543210abcdef",
                "Name": f"/{target}",
                "State": {"Status": "running", "Running": True, "Pid": 4128},
                "SizeRootFs": 76432100,
                "Config": {"Image": f"{target}:latest"},
                "NetworkSettings": {"IPAddress": "172.17.0.2"}
            }]
            return ExecutionResult(command, json.dumps(mock_inspect, indent=2), simulated=True)

        elif action == "volume":
            if "ls" in parts:
                lines = ["DRIVER    VOLUME NAME"]
                for v in self.mock_volumes:
                    lines.append(f"local     {v}")
                return ExecutionResult(command, "\n".join(lines), simulated=True)
            return ExecutionResult(command, f"Volume operation completed for {parts[-1]}", simulated=True)

        elif action == "logs":
            target = parts[-1]
            sample_logs = [
                f"[INFO] 2026-11-02 12:00:01 {target} service initialized",
                f"[INFO] 2026-11-02 12:00:03 listening on port 0.0.0.0:80",
                f"[INFO] 2026-11-02 12:05:12 health check OK (latency 1.2ms)"
            ]
            return ExecutionResult(command, "\n".join(sample_logs), simulated=True)

        return ExecutionResult(command, f"Executed successfully: {command}", simulated=True)


class LuminaireMeshExecutor:
    """
    Simulates the proprietary Emergency Luminaires System (Section III-C1 & Table II).
    Supports all 53 command types: mesh status, individual luminaire controls,
    multicast grouping, battery autonomy & functional tests, sink configurations, and DBR.
    """

    def __init__(self):
        # Simulated mesh state
        self.provisioning_enabled = True
        self.ble_beacons_global = True
        self.diagnostics_interval = 60
        self.sink_count = 3
        self.luminaires = {}
        self.groups = {
            "actuator": [4, 18, 33],
            "emergency": [21, 22, 28, 5, 9, 14],
            "exit": [41, 42, 43, 44, 45, 50],
            "mainfloor": [3, 7, 9],
            "garage": [210, 211, 212, 213, 214, 215],
            "fireline": [2, 4, 10]
        }
        self.tests = {
            "10": {"name": "lightCheck", "type": "autonomy_odd", "active": True, "target": "51-55"},
            "12": {"name": "monthlyCheck", "type": "functional", "active": True, "target": "1-50"},
            "15": {"name": "deepAutonomy", "type": "autonomy", "active": False, "target": "all"}
        }

        # Seed initial luminaires (1 to 1200)
        random.seed(42)
        sample_ids = [4, 5, 6, 7, 8, 9, 10, 12, 20, 23, 26, 27, 30, 37, 43, 50, 57, 60, 67, 88, 94, 100, 145, 206, 270, 299, 310, 605, 911, 968, 1004, 1008, 1089, 1105]
        for lid in sample_ids:
            self.luminaires[lid] = {
                "id": lid,
                "state": "OFF",
                "brightness": 100,
                "battery": random.randint(85, 100),
                "dbr": False,
                "augmented": False,
                "ble": True,
                "pictogram": 0,
                "update_period": 30,
                "errors": []
            }

    def _ensure_luminaire(self, lid: int):
        if lid not in self.luminaires:
            self.luminaires[lid] = {
                "id": lid,
                "state": "OFF",
                "brightness": 100,
                "battery": 95,
                "dbr": False,
                "augmented": False,
                "ble": True,
                "pictogram": 0,
                "update_period": 30,
                "errors": []
            }

    def execute(self, command: str) -> ExecutionResult:
        cmd = command.strip()
        parts = cmd.split()
        if not parts:
            return ExecutionResult(command, "", "Empty command", returncode=1, simulated=True)

        verb = parts[0]

        # 1. Inspection and query
        if verb == "info" and len(parts) > 1:
            lid = int(parts[1]) if parts[1].isdigit() else 299
            self._ensure_luminaire(lid)
            lum = self.luminaires[lid]
            out = (
                f"LUMINAIRE ID: {lum['id']}\n"
                f"State: {lum['state']} | Brightness: {lum['brightness']}% | Battery: {lum['battery']}%\n"
                f"DBR: {'ENABLED' if lum['dbr'] else 'DISABLED'} | Augmented Security: {'ENABLED' if lum['augmented'] else 'DISABLED'}\n"
                f"BLE Beacons: {'ACTIVE' if lum['ble'] else 'INACTIVE'} | Pictogram Mode: {lum['pictogram']}\n"
                f"Update Period: {lum['update_period']}s | Active Errors: {len(lum['errors'])}"
            )
            return ExecutionResult(command, out, simulated=True)

        elif verb == "status":
            lid = int(parts[1]) if len(parts) > 1 and parts[1].isdigit() else None
            if lid:
                self._ensure_luminaire(lid)
                lum = self.luminaires[lid]
                return ExecutionResult(command, f"Luminaire {lid}: State={lum['state']}, Battery={lum['battery']}%, Errors={len(lum['errors'])}", simulated=True)
            return ExecutionResult(command, f"System Online: {len(self.luminaires)} registered nodes, Mesh Sinks: {self.sink_count}", simulated=True)

        elif verb == "get_luminaires":
            ids = sorted(list(self.luminaires.keys()))
            return ExecutionResult(command, f"Registered Luminaires ({len(ids)} nodes): {', '.join(str(i) for i in ids)}", simulated=True)

        elif verb == "get_luminaires_states":
            lines = ["ID    STATE   BATTERY   BRIGHTNESS   DBR   ERRORS"]
            for lid, l in sorted(self.luminaires.items())[:15]:
                lines.append(f"{lid:<5} {l['state']:<7} {l['battery']}%      {l['brightness']}%        {str(l['dbr']):<5} {len(l['errors'])}")
            return ExecutionResult(command, "\n".join(lines), simulated=True)

        elif verb == "get_mesh":
            mesh_diag = (
                "MESH CONNECTIVITY GRAPH:\n"
                "  Sink #1 [Master, MAC: 00:1B:44:11:3A:B7] <--> 14 Relay Nodes <--> 32 Leaf Nodes\n"
                "  Sink #2 [Backup, MAC: 00:1B:44:11:3A:B8] <--> 11 Relay Nodes <--> 28 Leaf Nodes\n"
                "  Sink #3 [Bridge, MAC: 00:1B:44:11:3A:B9] <--> 8 Relay Nodes  <--> 19 Leaf Nodes\n"
                "Mesh Protocol: 6LoWPAN / RPL | Average Link Quality: 96.4% | Packet Delivery: 99.8%"
            )
            return ExecutionResult(command, mesh_diag, simulated=True)

        elif verb == "reset_mesh":
            return ExecutionResult(command, "Mesh routing cache flushed. Re-initiating RPL DODAG discovery...", simulated=True)

        elif verb == "config_sink":
            return ExecutionResult(command, f"Standard configuration applied across all {self.sink_count} sinks successfully.", simulated=True)

        elif verb == "get_sinks":
            sinks = ["ID 1: Sink North (192.168.1.10) [ACTIVE]", "ID 2: Sink South (192.168.1.11) [STANDBY]", "ID 3: Sink Bridge (192.168.1.12) [ACTIVE]"]
            return ExecutionResult(command, "\n".join(sinks), simulated=True)

        elif verb == "zwp":
            return ExecutionResult(command, "ZWP Service Status: ACTIVE (PID: 1042, Port: 8443, Mesh: Online)", simulated=True)

        elif verb == "get_diagnostics":
            return ExecutionResult(command, f"Diagnostics Status: Healthy. Monitoring cycle: {self.diagnostics_interval}s. 0 fatal alerts.", simulated=True)

        elif verb == "set_diagnostics" and len(parts) > 1:
            self.diagnostics_interval = int(parts[1]) if parts[1].isdigit() else 60
            return ExecutionResult(command, f"Diagnostics reporting interval set to {self.diagnostics_interval} seconds.", simulated=True)

        # 2. Luminaire control
        elif verb == "on" and len(parts) > 1:
            lid = int(parts[1]) if parts[1].isdigit() else 1
            self._ensure_luminaire(lid)
            self.luminaires[lid]["state"] = "ON"
            return ExecutionResult(command, f"Luminaire {lid}: Emergency light switched ON.", simulated=True)

        elif verb == "off" and len(parts) > 1:
            lid = int(parts[1]) if parts[1].isdigit() else 1
            self._ensure_luminaire(lid)
            self.luminaires[lid]["state"] = "OFF"
            return ExecutionResult(command, f"Luminaire {lid}: Emergency light switched OFF.", simulated=True)

        elif verb == "permanent_on" and len(parts) > 1:
            lid = int(parts[1]) if parts[1].isdigit() else 1
            self._ensure_luminaire(lid)
            self.luminaires[lid]["state"] = "PERMANENT_ON"
            return ExecutionResult(command, f"Luminaire {lid}: Switched to PERMANENT ON.", simulated=True)

        elif verb == "permanent_off" and len(parts) > 1:
            lid = int(parts[1]) if parts[1].isdigit() else 1
            self._ensure_luminaire(lid)
            self.luminaires[lid]["state"] = "PERMANENT_OFF"
            return ExecutionResult(command, f"Luminaire {lid}: Switched to PERMANENT OFF.", simulated=True)

        elif verb == "set_brightness" and len(parts) > 2:
            lid = int(parts[1]) if parts[1].isdigit() else 1
            b_val = int(parts[2]) if parts[2].isdigit() else 100
            self._ensure_luminaire(lid)
            self.luminaires[lid]["brightness"] = b_val
            return ExecutionResult(command, f"Luminaire {lid}: Brightness set to {b_val}%.", simulated=True)

        elif verb == "set_period" and len(parts) > 2:
            lid, sec = int(parts[1]), int(parts[2])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["update_period"] = sec
            return ExecutionResult(command, f"Luminaire {lid}: Telemetry update period set to {sec}s.", simulated=True)

        elif verb == "set_pictogram" and len(parts) > 2:
            lid, picto = int(parts[1]), int(parts[2])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["pictogram"] = picto
            return ExecutionResult(command, f"Luminaire {lid}: Direction pictogram updated to symbol {picto}.", simulated=True)

        elif verb == "dbr_on" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["dbr"] = True
            return ExecutionResult(command, f"Luminaire {lid}: Dynamic Brightness Regulation (DBR) ENABLED.", simulated=True)

        elif verb == "dbr_off" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["dbr"] = False
            return ExecutionResult(command, f"Luminaire {lid}: Dynamic Brightness Regulation (DBR) DISABLED.", simulated=True)

        elif verb == "augmented_on" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["augmented"] = True
            return ExecutionResult(command, f"Luminaire {lid}: Augmented Security Mode ACTIVATED.", simulated=True)

        elif verb == "augmented_off" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["augmented"] = False
            return ExecutionResult(command, f"Luminaire {lid}: Augmented Security Mode DEACTIVATED.", simulated=True)

        elif verb == "enable_beacons" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["ble"] = True
            return ExecutionResult(command, f"Luminaire {lid}: BLE Discovery Beacon ENABLED.", simulated=True)

        elif verb == "disable_beacons" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["ble"] = False
            return ExecutionResult(command, f"Luminaire {lid}: BLE Discovery Beacon DISABLED.", simulated=True)

        elif verb == "reset_errors" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            self.luminaires[lid]["errors"] = []
            return ExecutionResult(command, f"Luminaire {lid}: Error registers cleared.", simulated=True)

        elif verb == "add_luminaire" and len(parts) > 1:
            lid = int(parts[1])
            self._ensure_luminaire(lid)
            return ExecutionResult(command, f"Luminaire {lid} successfully registered to mesh network.", simulated=True)

        elif verb == "delete_luminaire" and len(parts) > 1:
            lid = int(parts[1])
            if lid in self.luminaires:
                del self.luminaires[lid]
            return ExecutionResult(command, f"Luminaire {lid} removed from system.", simulated=True)

        elif verb == "purge_luminaires":
            self.luminaires.clear()
            return ExecutionResult(command, "All luminaire configurations purged from network.", simulated=True)

        # 3. Multicast Groups
        elif verb == "get_groups":
            out = [f"Group '{name}': {len(nodes)} luminaires ({nodes})" for name, nodes in self.groups.items()]
            return ExecutionResult(command, "\n".join(out), simulated=True)

        elif verb == "get_group" and len(parts) > 1:
            name = parts[1]
            nodes = self.groups.get(name, [])
            return ExecutionResult(command, f"Group '{name}': luminaires {nodes}", simulated=True)

        elif verb == "add_group" and len(parts) > 2:
            name = parts[1]
            nodes_str = parts[2]
            self.groups[name] = nodes_str
            return ExecutionResult(command, f"Group '{name}' created with luminaires: {nodes_str}", simulated=True)

        elif verb == "delete_group" and len(parts) > 1:
            name = parts[1]
            self.groups.pop(name, None)
            return ExecutionResult(command, f"Group '{name}' removed.", simulated=True)

        # 4. Tests
        elif verb == "start_functional_test":
            lid = parts[1] if len(parts) > 1 else "all"
            duration = parts[2] if len(parts) > 2 else "60"
            return ExecutionResult(command, f"Functional test launched on luminaire {lid} for {duration} seconds. Status: RUNNING", simulated=True)

        elif verb == "start_autonomy_test":
            lid = parts[1] if len(parts) > 1 else "all"
            duration = parts[2] if len(parts) > 2 else "200"
            return ExecutionResult(command, f"Battery autonomy test started on luminaire {lid} ({duration}s duration). Battery discharging under test load.", simulated=True)

        elif verb in ("stop_functional_test", "stop_autonomy_test"):
            lid = parts[1] if len(parts) > 1 else "all"
            return ExecutionResult(command, f"Test stopped on luminaire {lid}. Restoring normal operation.", simulated=True)

        elif verb == "get_test_results":
            out = (
                "TEST RESULTS SUMMARY:\n"
                "  Test #10 (Autonomy 60min): PASS (Average battery retention: 91%)\n"
                "  Test #12 (Functional): PASS (Lamp strike time: 42ms)\n"
                "  Test #15 (Full Autonomy): 34/34 nodes passed, 0 failures."
            )
            return ExecutionResult(command, out, simulated=True)

        elif verb == "get_tests":
            out = [f"Test ID {tid}: Name='{t['name']}', Type='{t['type']}', Active={t['active']}" for tid, t in self.tests.items()]
            return ExecutionResult(command, "\n".join(out), simulated=True)

        elif verb == "enable_provisioning":
            self.provisioning_enabled = True
            return ExecutionResult(command, "Mesh provisioning ENABLED: dynamic device joining permitted.", simulated=True)

        elif verb == "disable_provisioning":
            self.provisioning_enabled = False
            return ExecutionResult(command, "Mesh provisioning DISABLED: network locked to current devices.", simulated=True)

        elif verb == "get_provisioning":
            status = "ENABLED" if self.provisioning_enabled else "DISABLED"
            return ExecutionResult(command, f"Provisioning state: {status}. Pending join queue: 0 devices.", simulated=True)

        elif verb == "help":
            target = parts[1] if len(parts) > 1 else "general"
            return ExecutionResult(command, f"Help manual for '{target}': usage and parameter options available.", simulated=True)

        elif verb == "exit":
            return ExecutionResult(command, "CLI session terminated.", simulated=True)

        return ExecutionResult(command, f"Luminaire Mesh Command Executed: {command}", simulated=True)


class ShellExecutor:
    """Unified dispatcher for Docker and Luminaire command execution."""

    def __init__(self, force_mock: bool = False):
        self.docker = DockerExecutor(force_mock=force_mock)
        self.luminaires = LuminaireMeshExecutor()

    def execute(self, command: str, context: Optional[str] = None) -> ExecutionResult:
        cmd = command.strip()
        if context == "docker" or cmd.startswith("docker"):
            return self.docker.execute(cmd)
        else:
            return self.luminaires.execute(cmd)
